"""Validation on real patients: MIMIC-IV demo heart-failure ICU stays.

The simulated experiments (pipeline.py) test the twin against ground truth
generated by its own physics.  These do not: the patients are real, the
chart is what their nurses recorded, and the answers are measurements the
twin never sees.

  forecast      Fit on the chart so far, predict the next round's vitals,
                including drugs actually started in between.  Compared with
                persistence ("nothing changes") -- the baseline to beat.
  held_out      Twin estimates vs measurements withheld from it: CVP for the
                congestion axis, cardiac index for perfusion, PA diastolic
                pressure as a proxy for wedge pressure.
  concordance   When clinicians started a diuretic or an inotrope, had the
                twin -- fitted only on the chart before that moment -- already
                read the patient as wet, or as cold?

Real ICU patients are treated continuously and the twin models a small
formulary, so none of this is a clean test of physiology alone.  The
numbers are reported as they come out.
"""

from __future__ import annotations

import numpy as np

from .core.cardiac import CardiacParams
from .core.interventions import Plan
from .data.mimic import load_hf_stays
from .models.estimator import fit_twin, shared_inverse

WINDOW = 12          # fit on the most recent 12 rounds (48 h at 4-hourly)
CMH2O_PER_MMHG = 1.36


def fit_real(stay, chart: list):
    template = CardiacParams(bsa=stay.bsa, c_diastolic=14.0, edv_max=295.0)
    return fit_twin(str(stay.stay_id), chart[-WINDOW:], template=template, inverse=shared_inverse())


_CHARTS: dict = {}
_FITS: dict = {}


def _chart(stay, cadence_h: float) -> list:
    key = (stay.stay_id, cadence_h)
    if key not in _CHARTS:
        _CHARTS[key] = stay.chart(cadence_h)
    return _CHARTS[key]


def _fit_at(stay, cadence_h: float, i: int):
    """Twin fitted on rounds 0..i -- shared by all three experiments."""
    key = (stay.stay_id, cadence_h, i)
    if key not in _FITS:
        _FITS[key] = fit_real(stay, _chart(stay, cadence_h)[: i + 1])
    return _FITS[key]


def _stats(pred, true) -> dict:
    pred, true = np.asarray(pred, float), np.asarray(true, float)
    if len(pred) < 3:
        return {"n": int(len(pred))}
    return {
        "n": int(len(pred)),
        "r": float(np.corrcoef(pred, true)[0, 1]),
        "mae": float(np.mean(np.abs(pred - true))),
        "bias": float(np.mean(pred - true)),
    }


# --------------------------------------------------------------------------
# 1. Next-round forecast
# --------------------------------------------------------------------------

def forecast_experiment(cadence_h: float = 4.0, min_history: int = 3) -> dict:
    channels = ("hr", "sbp", "dbp", "map")
    err = {k: {"twin": [], "twin_no_drugs": [], "persistence": []} for k in channels}
    direction = {"hit": 0, "n": 0}
    with_drugs = 0

    for stay in load_hf_stays():
        chart = _chart(stay, cadence_h)
        for i in range(min_history - 1, len(chart) - 1):
            now, nxt = chart[i], chart[i + 1]
            dt = nxt.t - now.t
            twin = _fit_at(stay, cadence_h, i)
            starts = stay.drugs_started(now.t, nxt.t)
            plan = Plan(orders=tuple(starts))
            with_drugs += bool(starts)

            with_plan = twin.project(hours=dt, plan=plan)
            without = twin.project(hours=dt)
            actual = {"hr": nxt.hr, "sbp": nxt.sbp, "dbp": nxt.dbp, "map": nxt.map}
            last = {"hr": now.hr, "sbp": now.sbp, "dbp": now.dbp, "map": now.map}

            def read(tr):
                h, s = tr.hemo[-1], tr.states[-1]
                return {"hr": s.hr, "sbp": h.sbp, "dbp": h.dbp, "map": h.map}

            p_twin, p_bare = read(with_plan), read(without)
            for k in channels:
                err[k]["twin"].append(abs(p_twin[k] - actual[k]))
                err[k]["twin_no_drugs"].append(abs(p_bare[k] - actual[k]))
                err[k]["persistence"].append(abs(last[k] - actual[k]))

            change = actual["map"] - last["map"]
            if abs(change) >= 5.0:
                direction["n"] += 1
                direction["hit"] += int(np.sign(p_twin["map"] - last["map"]) == np.sign(change))

    out = {"forecasts": len(err["map"]["twin"]), "with_drug_starts": with_drugs}
    for k in channels:
        out[k] = {m: float(np.mean(v)) for m, v in err[k].items()}
        out[k]["twin_beats_persistence"] = float(np.mean(
            np.array(err[k]["twin"]) < np.array(err[k]["persistence"])))
    out["map_direction"] = {
        "n": direction["n"],
        "accuracy": direction["hit"] / direction["n"] if direction["n"] else None,
    }
    return out


# --------------------------------------------------------------------------
# 2. Hidden state against withheld measurements
# --------------------------------------------------------------------------

def held_out_experiment(cadence_h: float = 4.0, min_history: int = 2) -> dict:
    pairs = {"cvp": ([], [], []), "ci": ([], [], []), "pa_dia": ([], [], [])}
    cold = {"tp": 0, "fn": 0, "fp": 0, "tn": 0}

    for stay in load_hf_stays():
        chart = _chart(stay, cadence_h)
        for i in range(min_history - 1, len(chart)):
            t = chart[i].t
            cvp = stay.held("cvp", t)
            ci = stay.held("ci_nicom", t)
            if np.isnan(ci):
                for co_name in ("co_thermo", "co_cont", "co_nicom"):
                    co = stay.held(co_name, t)
                    if not np.isnan(co):
                        ci = co / stay.bsa
                        break
            pa = stay.held("pa_dia", t)
            if np.isnan(cvp) and np.isnan(ci) and np.isnan(pa):
                continue

            h = _fit_at(stay, cadence_h, i).hemodynamics
            for name, measured, estimate in (
                ("cvp", cvp, h.jvp_cm / CMH2O_PER_MMHG),
                ("ci", ci, h.cardiac_index),
                ("pa_dia", pa, h.pcwp),
            ):
                if not np.isnan(measured):
                    pairs[name][0].append(estimate)
                    pairs[name][1].append(measured)
                    pairs[name][2].append(stay.stay_id)
            if not np.isnan(ci):
                truly, says = ci < 2.2, h.cardiac_index < 2.2
                cold["tp" if truly and says else "fn" if truly else "fp" if says else "tn"] += 1

    out = {}
    for name, (est, meas, stays) in pairs.items():
        counts = sorted((stays.count(s) for s in set(stays)), reverse=True)
        # Points cluster in few patients; report how concentrated they are.
        out[name] = {**_stats(est, meas), "stays": len(counts), "points_per_stay": counts}
    # Confusion, not an agreement rate: with few truly cold readings, agreement
    # is dominated by "both warm" and says nothing about catching cold patients.
    out["cold_confusion"] = cold
    return out


# --------------------------------------------------------------------------
# 3. Did the twin see what the clinicians acted on?
# --------------------------------------------------------------------------

def concordance_experiment(cadence_h: float = 4.0, min_history: int = 2) -> dict:
    """Twin profile at the round before a treatment started, vs all rounds."""
    base = {"wet": [], "cold": []}
    at = {"furosemide": {"wet": [], "cold": []},
          "inotrope": {"wet": [], "cold": []},
          "vasopressor": {"wet": [], "cold": []}}
    group = {"furosemide": "furosemide", "dobutamine": "inotrope", "milrinone": "inotrope",
             "noradrenaline": "vasopressor"}

    for stay in load_hf_stays():
        chart = _chart(stay, cadence_h)

        def profile(i):
            h = _fit_at(stay, cadence_h, i).hemodynamics
            return h.pcwp > 18.0, h.cardiac_index < 2.2

        for i in range(min_history - 1, len(chart)):
            wet, cold = profile(i)
            base["wet"].append(wet)
            base["cold"].append(cold)

        for t, key, new in stay.drugs:
            if not new or key not in group:
                continue
            prior = [i for i, o in enumerate(chart) if o.t <= t]
            if len(prior) < min_history:
                continue
            wet, cold = profile(prior[-1])
            at[group[key]]["wet"].append(wet)
            at[group[key]]["cold"].append(cold)

    rate = lambda v: float(np.mean(v)) if v else None
    return {
        "all_rounds": {"n": len(base["wet"]), "wet": rate(base["wet"]), "cold": rate(base["cold"])},
        **{g: {"n": len(v["wet"]), "wet": rate(v["wet"]), "cold": rate(v["cold"])} for g, v in at.items()},
    }


def cohort_summary() -> dict:
    stays = load_hf_stays()
    charts = [s.chart(4.0) for s in stays]
    return {
        "stays": len(stays),
        "patients": len({s.subject_id for s in stays}),
        "rounds": int(sum(len(c) for c in charts)),
        "median_los_days": float(np.median([s.los_h / 24 for s in stays])),
        "median_age": float(np.median([s.age for s in stays])),
        "women": int(sum(s.sex == "female" for s in stays)),
    }
