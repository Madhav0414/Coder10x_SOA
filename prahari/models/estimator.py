"""Recovering a twin's state from the ward chart.

Three steps, cheapest first:

  1. Learned inverse -- gradient-boosted regressors, trained on simulated
     physiology (no patient data), map one observation to a parameter guess.
  2. Snapshot refinement -- bounded least squares drives the forward model
     onto each observation in turn, warm-started from the previous one.
  3. Joint assimilation -- one trajectory (level + linear trend per
     time-varying parameter, arterial compliance constant) fitted to every
     observation at once, each channel weighted by its measurement noise,
     older readings down-weighted.  Its levels are the current state; its
     trends give the rate of decline and the fluid the patient is running at.

Why step 3 exists: cardiac index comes mostly from cuff pulse pressure, which
a manual cuff reads with ~25% noise in a sick patient.  Trusting the latest
reading alone gave a cardiac-index error of ~0.55 L/min/m2 and missed
deteriorating patients; fitting the whole chart roughly halves it.

Why the bedside signs matter: filling pressure is not identifiable from a
BP cuff, and perfusion only weakly.  JVP, oedema and weight identify the wet
axis; capillary refill the cold axis -- the same signs clinicians use for the
Stevenson profile.

The residual of the fit feeds the twin's confidence.
"""


from __future__ import annotations

import pickle
import threading
from dataclasses import replace
from pathlib import Path

import numpy as np
from scipy.optimize import least_squares

from ..core.cardiac import G_HR, G_SVR, MAP_SETPOINT, CardiacParams, solve_hemodynamics
from ..core.twin import Observation, PatientTwin

# Chance each channel is blanked when training the inverse on gappy charts.
#                     hr  sbp  dbp  spo2 rr   jvp  edema weight crt
MISSING_P = np.array([0., 0., 0., 0.3, 0.3, 0.5, 0.3, 0.5, 0.3])

# Fitted parameters, in order, with physiological bounds.
PARAM_NAMES = ("emax", "svr", "v_central", "hr", "v_interstitial")
LOWER = np.array([0.20, 8.0, 200.0, 40.0, 0.0])
UPPER = np.array([3.00, 40.0, 1400.0, 165.0, 2500.0])

# Observation weighting: trust a pulse oximeter more than a manual cuff.
# Congestion signs carry heavy weight: they are the ONLY observations that
# identify filling pressure.  Without them, volume state is unrecoverable from
# a blood-pressure cuff and the twin cannot tell wet from dry.
OBS_WEIGHTS = np.array([1.0, 0.9, 0.9, 1.4, 1.1, 2.2, 1.6, 1.8, 1.5])


def _predict_obs(params: CardiacParams) -> np.ndarray:
    h = solve_hemodynamics(params)
    return np.array([
        params.hr, h.sbp, h.dbp, h.spo2, h.resp_rate,
        h.jvp_cm, h.edema_grade, h.weight_excess_kg, h.crt_s,
    ])


def _observed(obs: Observation) -> np.ndarray:
    return np.array([
        obs.hr, obs.sbp, obs.dbp, obs.spo2, obs.resp_rate,
        obs.jvp_cm, obs.edema_grade, obs.weight_excess_kg, obs.crt_s,
    ])


def _residuals(x: np.ndarray, template: CardiacParams, target: np.ndarray) -> np.ndarray:
    trial = replace(
        template,
        emax=float(x[0]), svr=float(x[1]), v_central=float(x[2]),
        hr=float(x[3]), v_interstitial=float(x[4]),
    )
    r = (_predict_obs(trial) - target) * OBS_WEIGHTS
    r[np.isnan(target)] = 0.0          # missing reading: no information, no penalty
    return r


# --------------------------------------------------------------------------
# Stage 1 -- the learned inverse operator
# --------------------------------------------------------------------------

class LearnedInverse:
    """Maps observations to parameters, trained on the forward model itself.

    Because the training data is generated by simulation rather than collected
    from patients, this carries no privacy burden at all -- which matters under
    India's DPDP Act.
    """

    VERSION = 4   # bump when the features or training data change

    def __init__(self) -> None:
        self.version = self.VERSION
        self.models = {}
        self.trained = False
        self.train_r2 = {}

    def fit(self, n: int = 6000, seed: int = 11, verbose: bool = False) -> "LearnedInverse":
        from sklearn.ensemble import HistGradientBoostingRegressor
        from sklearn.metrics import r2_score

        rng = np.random.default_rng(seed)
        X, Y = [], []

        for _ in range(n):
            vec = LOWER + rng.random(5) * (UPPER - LOWER)
            p = CardiacParams(
                emax=vec[0], emax_base=vec[0], svr=vec[1], svr_base=vec[1],
                v_central=vec[2], hr=vec[3], hr_base=vec[3], v_interstitial=vec[4],
                c_arterial=float(rng.uniform(1.1, 2.1)),
                c_venous=float(rng.uniform(27.0, 40.0)),
                c_diastolic=float(rng.uniform(9.0, 17.0)),
                bsa=float(rng.uniform(1.35, 2.0)),
                edv_max=float(rng.uniform(200.0, 340.0)),
            )
            obs = _predict_obs(p)
            if not np.all(np.isfinite(obs)):
                continue
            # The estimator sees the same noisy, rounded numbers a nurse records.
            obs = obs + rng.normal(0, [2.5, 5.0, 4.0, 1.2, 1.8, 1.5, 0.35, 0.4, 0.6])
            # Real charts have gaps (oxygen masks SpO2, ventilators set the
            # breathing rate, signs go uncharted).  Train on gaps too.
            obs[rng.random(9) < MISSING_P] = np.nan
            X.append(np.concatenate([obs, [p.bsa]]))
            Y.append(vec)

        X, Y = np.asarray(X), np.asarray(Y)
        split = int(0.85 * len(X))

        for i, name in enumerate(PARAM_NAMES):
            m = HistGradientBoostingRegressor(
                max_iter=260, learning_rate=0.08, max_depth=7, random_state=seed
            )
            m.fit(X[:split], Y[:split, i])
            self.models[name] = m
            self.train_r2[name] = float(r2_score(Y[split:, i], m.predict(X[split:])))
            if verbose:
                print(f"  inverse[{name}] holdout R2 = {self.train_r2[name]:.3f}")

        self.trained = True
        return self

    def predict(self, obs: Observation, bsa: float) -> np.ndarray:
        feat = np.array([[
            obs.hr, obs.sbp, obs.dbp, obs.spo2, obs.resp_rate,
            obs.jvp_cm, obs.edema_grade, obs.weight_excess_kg, obs.crt_s, bsa,
        ]])
        return np.array(
            [float(self.models[name].predict(feat)[0]) for name in PARAM_NAMES]
        )


_SHARED_INVERSE: LearnedInverse | None = None
_LOCK = threading.Lock()
_CACHE_FILE = Path(__file__).resolve().parents[2] / ".cache" / "inverse.pkl"


def shared_inverse(verbose: bool = False) -> LearnedInverse:
    """One trained inverse operator, reused across the ward.

    Cached to disk after the first fit.  A stale or incompatible cache (e.g.
    after a scikit-learn upgrade) is ignored and rebuilt.
    """
    global _SHARED_INVERSE
    with _LOCK:
        if _SHARED_INVERSE is not None:
            return _SHARED_INVERSE
        if _CACHE_FILE.exists():
            try:
                with open(_CACHE_FILE, "rb") as fh:
                    cached = pickle.load(fh)
                if (isinstance(cached, LearnedInverse) and cached.trained
                        and getattr(cached, "version", 0) == LearnedInverse.VERSION):
                    _SHARED_INVERSE = cached
                    return cached
            except Exception:
                pass
        inv = LearnedInverse().fit(verbose=verbose)
        try:
            _CACHE_FILE.parent.mkdir(parents=True, exist_ok=True)
            with open(_CACHE_FILE, "wb") as fh:
                pickle.dump(inv, fh)
        except OSError:
            pass
        _SHARED_INVERSE = inv
        return inv


# --------------------------------------------------------------------------
# Stage 2 -- physics refinement
# --------------------------------------------------------------------------

def fit_single(
    obs: Observation,
    template: CardiacParams,
    inverse: LearnedInverse | None = None,
) -> tuple:
    """Recover parameters from one charted observation. Returns (params, rmse)."""
    target = _observed(obs)

    if inverse is not None and inverse.trained:
        x0 = np.clip(inverse.predict(obs, template.bsa), LOWER, UPPER)
    else:
        x0 = np.array([template.emax, template.svr, template.v_central,
                       obs.hr, template.v_interstitial])
        x0 = np.clip(x0, LOWER, UPPER)

    sol = least_squares(
        _residuals, x0, args=(template, target),
        bounds=(LOWER, UPPER), max_nfev=140, xtol=1e-8, ftol=1e-8,
    )

    fitted = replace(
        template,
        emax=float(sol.x[0]), svr=float(sol.x[1]), v_central=float(sol.x[2]),
        hr=float(sol.x[3]), v_interstitial=float(sol.x[4]),
    )
    seen = ~np.isnan(target)
    rmse = float(np.sqrt(np.mean((sol.fun[seen] / OBS_WEIGHTS[seen]) ** 2)))
    return fitted, rmse


# Measurement noise (1 SD) of each charted channel, as a ward records them:
# manual cuff, finger oximeter, counted breaths, eyeballed JVP and oedema,
# ward scale.  Used to weight the joint fit so each reading counts in
# proportion to how much it can be trusted.
#                  sbp  dbp  spo2  rr   jvp  edema weight crt
SIGMA = np.array([5.0, 4.0, 1.3, 1.9, 1.6, 0.38, 0.42, 0.65])

# Older readings count for less: weight exp(dt / FORGET_H), dt <= 0.
FORGET_H = 16.0

# Channel switches, for ablation.  Everything on in normal use.
USE_CRT = True

#            emax  d_emax  v     d_v   svr  d_svr  vi    d_vi  c_art
_JLO = np.array([0.20, -0.10, 200.0, -60.0, 8.0, -2.0, 0.0, -80.0, 0.90])
_JHI = np.array([3.00, 0.06, 1400.0, 60.0, 40.0, 2.0, 2500.0, 80.0, 2.40])
# Priors: slopes shrink toward zero and compliance toward the population mean
# unless the data say otherwise.  Matters most when only a reading or two exist.
_PRIOR_MU = np.array([1.5])
_PRIOR = {"d_emax": 0.03, "d_v": 30.0, "d_svr": 1.0, "d_vi": 30.0, "c_art": 0.20}


def _state_at(x, dt, template, hr):
    emax, d_emax, v, d_v, svr, d_svr, vi, d_vi, c_art = x
    return replace(
        template,
        emax=float(np.clip(emax + d_emax * dt, 0.15, 3.5)),
        v_central=float(np.clip(v + d_v * dt, 150.0, 1600.0)),
        svr=float(np.clip(svr + d_svr * dt, 6.0, 45.0)),
        v_interstitial=float(max(0.0, vi + d_vi * dt)),
        c_arterial=float(c_art),
        hr=float(hr),
    )


def _obs7(obs):
    return np.array([obs.sbp, obs.dbp, obs.spo2, obs.resp_rate,
                     obs.jvp_cm, obs.edema_grade, obs.weight_excess_kg, obs.crt_s])


def _pred7(p):
    h = solve_hemodynamics(p)
    return np.array([h.sbp, h.dbp, h.spo2, h.resp_rate,
                     h.jvp_cm, h.edema_grade, h.weight_excess_kg, h.crt_s])


def assimilate(observations: list, template: CardiacParams, x0: np.ndarray):
    """Fit one trajectory to every reading at once.

    Each time-varying parameter is a level at the latest reading plus a
    linear trend; arterial compliance is a per-patient constant.  Heart rate
    is measured directly and enters as a known input.  Returns (x, rmse)
    where rmse is the raw residual of the most recent reading.
    """
    t_now = observations[-1].t
    dts = np.array([o.t - t_now for o in observations])
    wts = np.sqrt(np.exp(dts / FORGET_H))
    targets = [_obs7(o) for o in observations]

    sigma = SIGMA.copy()
    if not USE_CRT:
        sigma[7] = 1e9

    masks = [np.isnan(y) for y in targets]

    def residuals(x):
        out = []
        for o, dt, w, y, miss in zip(observations, dts, wts, targets, masks):
            r = w * (_pred7(_state_at(x, dt, template, o.hr)) - y) / sigma
            r[miss] = 0.0
            out.append(r)
        out.append(np.array([
            x[1] / _PRIOR["d_emax"], x[3] / _PRIOR["d_v"], x[5] / _PRIOR["d_svr"],
            x[7] / _PRIOR["d_vi"], (x[8] - _PRIOR_MU[0]) / _PRIOR["c_art"],
        ]))
        return np.concatenate(out)

    sol = least_squares(residuals, np.clip(x0, _JLO, _JHI), bounds=(_JLO, _JHI),
                        max_nfev=400, x_scale="jac")
    last = _pred7(_state_at(sol.x, 0.0, template, observations[-1].hr)) - targets[-1]
    last = last[~np.isnan(last)]
    return sol.x, float(np.sqrt(np.mean(last ** 2))) if last.size else 0.0


def fit_twin(
    patient_id: str,
    observations: list,
    template: CardiacParams | None = None,
    inverse: LearnedInverse | None = None,
) -> PatientTwin:
    """Build a synchronised twin from a patient chart.

    Snapshot inversions give a starting point; `assimilate` then fits the
    whole chart jointly.  The fitted trends set how fast contractility is
    falling and the fluid the patient is running at, which is what lets the
    forward simulation carry the slide on instead of freezing the snapshot.
    """
    template = template or CardiacParams()
    if not observations:
        return PatientTwin(patient_id, template)

    obs_sorted = sorted(observations, key=lambda o: o.t)
    inverse = inverse or shared_inverse()

    fits, running = [], template
    for o in obs_sorted:
        fitted, _ = fit_single(o, running, inverse=inverse)
        fits.append(fitted)
        running = fitted

    # Initial guess: recent snapshot levels, trends from a straight line.
    times = np.array([o.t for o in obs_sorted]) - obs_sorted[-1].t

    def level_slope(vals):
        vals = np.asarray(vals, dtype=float)
        if len(vals) < 2 or np.ptp(times) < 1e-6:
            return float(vals[-1]), 0.0
        slope, icpt = np.polyfit(times, vals, 1)
        return float(icpt), float(slope)

    e0, de = level_slope([f.emax for f in fits])
    v0, dv = level_slope([f.v_central for f in fits])
    s0, ds = level_slope([f.svr for f in fits])
    i0, di = level_slope([f.v_interstitial for f in fits])
    x0 = np.array([e0, de, v0, dv, s0, ds, max(0.0, i0), di, template.c_arterial])

    x, rmse = assimilate(obs_sorted, template, x0)
    emax, d_emax, v, d_v, svr, d_svr, vi, d_vi, c_art = x
    current = _state_at(x, 0.0, template, obs_sorted[-1].hr)
    h = solve_hemodynamics(current)

    progression = float(np.clip(-d_emax / max(emax, 1e-3), -0.02, 0.08))
    # Total fluid (vascular + interstitial) changes by intake minus urine;
    # urine follows perfusion pressure exactly as the ODE has it.
    urine = 55.0 * float(np.clip(h.map / 85.0, 0.25, 1.4))
    intake = float(np.clip(d_v + d_vi + urine, 10.0, 250.0))

    # Baselines the baroreflex regulates around, backed out so that the fitted
    # present is an equilibrium of the model.  Taking them from averages
    # instead makes every forecast open with a spurious hour-long correction.
    err = (MAP_SETPOINT - h.map) / MAP_SETPOINT
    current = replace(
        current,
        emax_base=current.emax,
        hr_base=float(current.hr / max(0.3, 1.0 + G_HR * err)),
        svr_base=float(current.svr / max(0.3, 1.0 + G_SVR * err)),
    )

    return PatientTwin(
        patient_id=patient_id,
        params=current,
        observations=obs_sorted,
        fit_residual=rmse,
        fit_n_obs=len(obs_sorted),
        progression_per_h=progression,
        intake_base=intake,
    )
